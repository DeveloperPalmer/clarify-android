package ru.sla.clarify.app.data.entity

/**
 * Событие вместе с его местом в общей очереди сервера.
 *
 * [seq] живёт снаружи события, а не полем внутри него: нумерация — забота транспорта, и,
 * заведи мы её полем, она повторилась бы в каждой схеме спеки и попала бы в `oneOf` конвертом.
 */
data class SequencedEvent<out E>(
  val seq: Long,
  val event: E
)
