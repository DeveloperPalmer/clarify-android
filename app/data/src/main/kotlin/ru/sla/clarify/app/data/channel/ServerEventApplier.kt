package ru.sla.clarify.app.data.channel

import ru.sla.clarify.app.data.entity.SequencedEvent

/**
 * Кто применяет события канала к локальному состоянию.
 *
 * Возврат из [apply] означает «записано»: сразу после него канал двигает курсор, и переспросить
 * эти события будет уже нечем. Поэтому реализация обязана возвращаться только тогда, когда данные
 * действительно в базе, а не поставлены в очередь.
 *
 * Потребитель у канала один и живёт в `AppScope`. Подписывать сюда экранные репозитории нельзя:
 * курсор двигался бы, пока их экран закрыт, и события для них пропали бы навсегда. Читают они
 * по-прежнему из базы — так же, как читают сегодня.
 */
interface ServerEventApplier<in E> {

  suspend fun apply(events: List<SequencedEvent<E>>)

  /** Догон невозможен: перечитать состояние целиком. */
  suspend fun resync()
}
