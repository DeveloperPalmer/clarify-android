package ru.sla.clarify.feature.chronology.domain

import kotlinx.coroutines.flow.Flow
import ru.sla.clarify.feature.chronology.domain.entity.ChronologyHistory

interface ChronologyRepository {

  /**
   * Догружает ленты веток, которых ещё нет в кэше.
   *
   * Нужна потому, что на холодном старте их там нет **гарантированно**: коммиты ветки кладёт в кэш
   * репозиторий ветки, когда ветку открыли, а до тех пор известны только сами ветки. Это не редкий
   * случай, а состояние по умолчанию — граф без этой догрузки был бы одной магистралью.
   *
   * Подписка идёт за списком веток, а не берёт его один раз: на холодном старте хронология
   * открывается раньше, чем приедет первый снимок веток беседы.
   */
  suspend fun subscribeOnBranchCommits()

  /**
   * История беседы целиком — ветки, их ленты и участники.
   *
   * Своей подписки на изменения веток и коммитов магистрали здесь нет: хронология открывается
   * только из личного треда, и обе подписки уже держит его модель. Второй слушатель дал бы лишний
   * трафик и расхождение состояний между чатом и графом.
   */
  val history: Flow<ChronologyHistory>
}
