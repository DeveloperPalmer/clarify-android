package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Уровень детализации полотна — §5 брифа.
 *
 * Уровень **меняет раскладку**, а не только вид узлов: обзор ставит глифы вместо плашек и ужимает
 * зазоры с дорожками вчетверо. Одним масштабом обзора не бывает — диапазон 0.4×…2.5× оставляет
 * демо-граф в 7.6 раза шире экрана, а «вписать всё» на раскладке эпизодов потребовало бы 0.052×.
 *
 * Список узлов уровень при этом **не меняет**, и на этом стоит всё остальное: дорожки, цвета
 * идентичности, рёбра, засечки мини-карты и индексы узлов на обоих уровнях одни и те же.
 *
 * Третьего уровня — отдельных сообщений внутри раскрытого эпизода — здесь нет намеренно. Его никто
 * не производит, а значение, которого не бывает, эта фича уже однажды заводила: признак `dim` был
 * описан, не выставлен ни разу, и приглушённого эпизода на экране не существовало, хотя и поле, и
 * его чтение были на месте. LOD 3 приедет вместе со своей механикой раскрытия эпизода.
 */
@Immutable
enum class GraphLevel {

  /** Обзор: глиф вместо плашки, зазоры и дорожки вчетверо теснее. */
  Overview,

  /** Эпизоды: базовый уровень, плашка-кластер (§6.2 брифа). */
  Episodes
}
