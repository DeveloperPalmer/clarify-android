package ru.sla.clarify.feature.chronology.ui.entity

/**
 * Квантованная пауза между соседними узлами.
 *
 * Ось X полотна — порядковое время, а не абсолютное: реальная длительность паузы растянула бы
 * ночь на километры пустоты. Точная длительность выводится подписью, расстояние даёт только
 * порядок величины.
 */
enum class TimeGap {
  /** До пяти минут — реплики одной очереди. */
  Minutes,

  /** До часа. */
  Hour,

  /** До шести часов. */
  Hours,

  /** До суток. */
  Day,

  /** Больше суток — разрыв в разговоре. */
  Long
}
