package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Где камера стоит по времени и какую долю истории видно: два числа, из которых собирается рамка
 * мини-карты.
 *
 * Факт о камере, а не о том, кто его показывает: полотно не знает ни про мини-карту, ни про полосу,
 * на которой это рисуется, — ровно так же, как не знает про отладочную панель.
 *
 * [position] — доля **хода**, а не координата: ноль означает «камера в начале истории», единица —
 * «в конце». Отсюда и правило, по которому рамка ставится на полосу: её левый край равен
 * `position · (полоса − ширина рамки)`. Ход рамки тогда сам подстраивается под её ширину — чем
 * крупнее масштаб, тем уже рамка, тем длиннее её ход и тем больше графа проезжает за каждый
 * пиксель. Края при этом совпадают с упорами камеры на любом масштабе, включая те, где рамка
 * расширена до размера пальца.
 *
 * Прежняя запись — доля мира и центр рамки на ней — этого не давала: рамку приходилось зажимать
 * краем полосы, и у каждого края набегало от 16 до 29.5 dp, где палец ещё едет, а граф уже стоит.
 *
 * @param position доля хода камеры по времени, от нуля до единицы
 * @param width ширина видимого, долей полосы; единица означает «видно всю историю»
 */
@Immutable
data class GraphViewportSpan(
  val position: Float,
  val width: Float
) {

  companion object {

    /** Видно всё: пустая история и содержимое, помещающееся в экран целиком. */
    val Full = GraphViewportSpan(position = 0f, width = 1f)
  }
}
