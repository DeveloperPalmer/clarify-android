package ru.sla.clarify.feature.chronology.ui.entity

/**
 * Состояние точки слияния на магистрали (§6.6 брифа).
 *
 * Два состояния, а не три: пока merge request открыт, места на магистрали нет вовсе — точка
 * появляется только с финализацией. [Pending] это кадр 3 церемонии, «место готово, ждёт», и вне
 * церемонии он живёт ровно столько, сколько играет её четвёртый кадр.
 */
enum class MergeNodeState {

  /** Кольцо ожидания: заливки нет, обводка золотом. */
  Pending,

  /** Слияние состоялось: залитая точка с иконкой. */
  Done
}
