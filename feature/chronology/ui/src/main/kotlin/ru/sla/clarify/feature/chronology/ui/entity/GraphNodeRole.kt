package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Чем узел является для раскладки: плашкой с содержимым или точкой на линии.
 *
 * Род нужен именно раскладке, а не только экрану. Точка ветвления и точка слияния обязаны быть
 * **настоящими узлами списка**, потому что накопительная ось X даёт каждому узлу собственный,
 * ни с кем не пересекающийся отрезок, — и только из этого следует, что вертикаль, поставленная на
 * центре такого узла, не может задеть чужую плашку. Точка, поставленная «где-то на магистрали между
 * узлами», этой гарантии не даёт.
 *
 * Уровень детализации здесь не кодируется: он записан в KDoc самих компонентов, иначе перевод узла
 * между уровнями стал бы переименованием.
 */
@Immutable
enum class GraphNodeRole {

  /** Кластер сообщений: плашка с содержимым. */
  Episode,

  /** Место на магистрали, откуда уходит ветка (§6.4 брифа). */
  Fork,

  /** Место на магистрали, где ветка вернулась в родителя (§6.6 брифа). */
  Merge,

  /** Последний узел магистрали — «сейчас» (§6.7 брифа). */
  Front
}
