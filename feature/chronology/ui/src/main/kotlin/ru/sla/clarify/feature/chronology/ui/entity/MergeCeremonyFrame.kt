package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Один кадр церемонии слияния — всё, что рисованию нужно знать о моменте времени (§12 брифа).
 *
 * **Доли, а не пиксели.** Ни одно поле здесь не выражено в координатах полотна, и это не стиль:
 * длину маршрута возврата даёт `PathMeasure`, то есть обёртка над `android.graphics.PathMeasure`,
 * чьи методы в `android.jar` — стабы. Функция, отдающая пиксели, юнит-тестом не покрывалась бы
 * вовсе, а вся арифметика этой фичи, оставшаяся без теста, рано или поздно ломалась. Поэтому доли
 * считаются отдельно, а на длину умножаются уже в фазе рисования — тот же приём, по которому
 * [GraphEdge] хранит числа, а не готовый `Path`.
 *
 * Семь кадров §12 делят **одну** шкалу и одни объекты, поэтому и полей здесь семь групп, а не семь
 * отдельных анимаций: раскадровка неделима, и разложить её на независимые переходы значило бы
 * позволить им разъехаться.
 *
 * @param dashSpeed множитель бега пунктира: `1` в покое, `3` на разгоне (кадр 1)
 * @param gold доля перехода цвета линии в `contentGoldPrimary` (кадр 1, возвращается кадром 7)
 * @param ring насколько проявлено кольцо ожидания на магистрали (кадр 3)
 * @param ringPulse фаза пульсации кольца, циклическая; `0` вне кадров 3 и 4
 * @param reach доля маршрута возврата, которая уже нарисована (кадр 4)
 * @param impact заливка кольца и масштаб иконки внутри него (кадр 5)
 * @param wave доля расхождения вспышки по магистрали; из неё же выводится её угасание (кадр 6)
 * @param exhale доля пути линии от полной силы к покою слитой ветки (кадр 7)
 */
@Immutable
data class MergeCeremonyFrame(
  val dashSpeed: Float,
  val gold: Float,
  val ring: Float,
  val ringPulse: Float,
  val reach: Float,
  val impact: Float,
  val wave: Float,
  val exhale: Float
)
