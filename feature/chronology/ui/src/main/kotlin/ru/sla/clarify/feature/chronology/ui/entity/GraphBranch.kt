package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Ветка графа с точки зрения раскладки: где она крепится к магистрали и как долго держит дорожку.
 *
 * **Идентичность ветки живёт здесь, а не в номере дорожки.** §4.2 брифа объявляет переиспользование
 * дорожки после слияния ключевым свойством, из-за которого граф не разрастается вниз бесконечно, — а
 * значит номер дорожки принадлежит не ветке, а отрезку времени. Пока ветку опознавали по дорожке,
 * это молча ломало три места сразу: соседние по ряду ветки получали ложное ребро, один цвет и одну
 * засечку на мини-карте.
 *
 * Цвет берётся из [colorIndex], а не из дорожки, и считается он `1 + (order - 1).mod(6)`, а не
 * `order.mod(6)`: ноль оставлен магистрали, и наивная формула красила бы шестую ветку переписки
 * цветом магистрали.
 *
 * @param id идентификатор ветки
 * @param colorIndex цвет идентичности: `0` у магистрали, `1…6` у веток (§7 брифа)
 * @param forkedFrom узел магистрали, от которого ветка ушла; `null`, когда сообщение-развилка
 *   удалено (§15 п. 10) или ещё не догружено
 * @param mergedAt узел магистрали, в котором ветка слилась; `null` у всех несмерженных
 * @param status что с веткой происходит: от него зависит и штрих линии, и то, отдаёт ли она дорожку
 */
@Immutable
data class GraphBranch(
  val id: Id,
  val colorIndex: Int,
  val forkedFrom: GraphNode.Id?,
  val mergedAt: GraphNode.Id?,
  val status: GraphBranchStatus
) {

  /** Идентификатор ветки: ключ группировки узлов и цель перехода в чат. */
  @JvmInline
  value class Id(val value: String)
}
