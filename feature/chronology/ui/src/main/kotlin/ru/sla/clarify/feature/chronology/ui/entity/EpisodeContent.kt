package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Что нарисовано внутри плашки эпизода.
 *
 * Интерфейс, а не класс: полотну и экрану нужен только этот набор величин, а откуда он взялся —
 * из временного набора или из собранного графа — их не касается. Пока это был конкретный мок,
 * временная модель протекала в публичное состояние экрана и не могла остаться internal.
 *
 * Всё уже приведено к тому виду, в котором рисуется: время — строкой, доля — числом от нуля до
 * единицы. Форматировать по дороге к плашке нечего.
 */
@Immutable
interface EpisodeContent {

  /** Время начала эпизода, готовое к показу. */
  val time: String

  /** Число сообщений в кластере. */
  val count: Int

  /** Последнее сообщение эпизода. */
  val snippet: String

  /** Доля своих реплик, от нуля до единицы. */
  val myShare: Float

  /** Счётчик непрочитанных; ноль — читать нечего. */
  val unreadCount: Long

  /** Эпизод внутри слитой ветки: рисуется приглушённым. */
  val dim: Boolean
}
