package ru.sla.clarify.feature.chronology.ui.components.canvas

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.unit.Velocity
import kotlin.math.sqrt

/**
 * Направление броска, зафиксированное в момент отпускания.
 *
 * Затухание идёт по **модулю** скорости, одномерно, а пройденный скаляр раскладывается по осям вот
 * этим вектором. Так траектория остаётся прямой под любым углом.
 *
 * Затухать покомпонентно нельзя, и это не вопрос вкуса: у платформенной кривой путь растёт как
 * `v^1.736`, поэтому у наклонного броска оси проходят непропорциональные расстояния за разное
 * время. Направление прилёта уезжает от направления броска на величину до 10.29°, траектория
 * выгибается, а в конце ломается в крючок, потому что одна ось уже встала. По-настоящему бесплатны
 * при таком затухании только 0° и 90°: даже на диагонали 45°, где направление сохраняется, бросок
 * не долетает 22.5%.
 *
 * Платформа раскладывает через угол: `abs(cos(atan2(vy, vx)) * s) * sign(vx)`. Здесь то же самое без
 * тригонометрии — `cos(atan2(vy, vx))` это и есть `vx / |v|`, а пара `abs` с `sign` ровно
 * восстанавливает знак. Разница только в том, что форма через единичный вектор верна и при
 * отрицательном скаляре, а платформенная — лишь пока он неотрицателен.
 *
 * @param velocity скорость отпускания в пикселях в секунду
 */
internal class FlingDirection(velocity: Velocity) {

  /** Модуль скорости: ровно то число, которое уходит в одномерное затухание. */
  val magnitude: Float = sqrt(velocity.x * velocity.x + velocity.y * velocity.y)

  /** Единичный вектор броска; при нулевой скорости вырождается в ноль. */
  val vector: Offset = if (magnitude > 0f) {
    Offset(x = velocity.x / magnitude, y = velocity.y / magnitude)
  } else {
    Offset.Zero
  }

  /**
   * Раскладывает пройденный вдоль броска путь по осям экрана.
   *
   * @param distance путь вдоль направления броска
   * @return то же расстояние в координатах экрана
   */
  fun offsetOf(distance: Float): Offset {
    return vector * distance
  }
}
