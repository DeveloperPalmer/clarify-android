package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.geometry.Offset

/**
 * Один шаг камеры: куда она встала и сколько из запрошенного взяла.
 *
 * Потреблённое возвращается вместе с новой камерой, а не выводится из неё вызывающим: у границы
 * разница между запрошенным и взятым — единственный признак, по которому затухание понимает, что
 * дальше ехать некуда. Без него анимация доигрывает свою длительность целиком, кормя камеру за
 * границей.
 *
 * @param requested запрошенное приращение
 * @param camera новый сдвиг содержимого, уже внутри диапазона
 * @param consumed часть [requested], которую камера отработала
 */
@Immutable
data class GraphPanStep(
  val requested: Offset,
  val camera: Offset,
  val consumed: Offset
) {

  /**
   * Отвергла ли камера шаг целиком.
   *
   * Признак живёт здесь, а не у того, кто его показывает: «упёрлись» — свойство самого шага, и
   * второе определение в телеметрии разъехалось бы с этим при первой же правке правила.
   *
   * Нулевой запрос отказом не считается: первый кадр затухания приходит с нулевым временем и
   * ничего не двигает по построению.
   */
  val isRejected: Boolean
    get() = requested != Offset.Zero && consumed == Offset.Zero
}
