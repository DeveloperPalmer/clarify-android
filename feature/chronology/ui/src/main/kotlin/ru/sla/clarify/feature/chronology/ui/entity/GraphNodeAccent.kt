package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Чем узел окрашен и куда смотрит: то, что нужно нарисовать узел, но не нужно, чтобы его разложить.
 *
 * Заведено потому, что у точки ветвления и точки слияния акцент **чужой**. Сами они стоят на
 * магистрали, а цветом и направлением обязаны показывать ветку, которая от них уходит или в них
 * возвращается (§6.4, §6.6 брифа) — иначе обводка кольца была бы нейтральной, а чип закрытой темы
 * не знал бы, с какой стороны магистрали ему висеть.
 *
 * Считается вместе с дорожками и по тем же данным, а не выводится узлом на месте: знать, какая
 * ветка от него ушла, узлу неоткуда, и цвет он получает готовым — так же, как получает его
 * `BranchNode`.
 *
 * @param lane дорожка, на которую смотрит узел: у плашки своя, у точки — дорожка её ветки. Знак
 *   говорит, с какой стороны магистрали живёт ветка
 * @param color цвет идентичности ветки, за которую узел говорит
 */
@Immutable
data class GraphNodeAccent(
  val lane: Int,
  val color: Color
)
