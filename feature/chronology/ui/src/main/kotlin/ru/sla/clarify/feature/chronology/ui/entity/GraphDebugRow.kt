package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Строка отладочной панели: подпись, значение и признак выхода за норму.
 *
 * Подпись и значение хранятся раздельно, а не собранной строкой: шрифт панели пропорциональный, и
 * выровнять колонки пробелами невозможно — выравнивает раскладка, по фиксированной ширине подписи.
 *
 * Аномалия отмечается на строке, а не сводится в один индикатор: важно не только что что-то не так,
 * а какая именно фаза Compose крутится — по общему флагу зависание не разобрать.
 *
 * @param label подпись метрики
 * @param value значение, уже приведённое к короткому виду
 * @param isAnomalous вышло ли значение за ожидаемый предел
 */
@Immutable
data class GraphDebugRow(
  val label: String,
  val value: String,
  val isAnomalous: Boolean = false
)
