package ru.sla.clarify.feature.chronology.ui.mapper

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import ru.sla.clarify.feature.chronology.ui.entity.GraphLevel
import ru.sla.clarify.feature.chronology.ui.entity.GraphLevelBand

/**
 * Шаг дорожки на этом уровне детализации.
 *
 * Обзор — это раскладка эпизодов, ужатая **вчетверо**: то же самое число делит и зазоры
 * (`TimeGap.toStepWidth`). Одно правило вместо двух таблиц, и оно пересказывается фразой, а не
 * списком литералов.
 *
 * Вчетверо — не подобранное число. При нём отношение охватов уровней на демо-наборе равно 6.23 при
 * отношении пределов масштаба 2.5 / 0.4 = 6.25, то есть стык уровней получается почти бесшовным по
 * охвату. Совпадение не случайно: обе величины задаёт одна и та же геометрия — плашка 200 dp против
 * глифа 14 dp при зазорах того же порядка.
 *
 * Ужимать вертикаль сильнее нельзя: на посадке глиф занимает 32 dp экрана, и шаг, ужатый до
 * бесшовности по вертикали, склеил бы соседние дорожки.
 *
 * @return расстояние между соседними дорожками
 */
internal fun GraphLevel.toLaneStep(): Dp {
  return when (this) {
    GraphLevel.Episodes -> 104.dp
    GraphLevel.Overview -> 26.dp
  }
}

/**
 * Масштаб покоя уровня: тот, к которому возвращает перелёт камеры.
 *
 * У эпизодов это единица — плашка нарисована в свою величину. У обзора единица не означает ничего:
 * покой там — «видно всё», то есть нижний край полосы, и зависит он от того, насколько длинна
 * история.
 *
 * Живёт здесь, рядом с шагом дорожки, а не у камеры: это такая же таблица уровня, как и остальные.
 * Камера покой получает числом — см. `flightScaleOf`.
 *
 * @param band полоса масштаба этого уровня
 * @return масштаб, ниже которого перелёт не опускает
 */
internal fun GraphLevel.toRestScale(band: GraphLevelBand): Float {
  return when (this) {
    GraphLevel.Episodes -> 1f
    GraphLevel.Overview -> band.min
  }
}
