package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Чем ребро является для читающего граф — и, как следствие, какой оно толщины.
 *
 * Роль отвечает **только** за толщину и за то, что линия означает. Цвет берётся из идентичности
 * ветки, штрих — из её статуса, и это две независимые оси §7 брифа: смешать их значило бы, что
 * зелёная линия сообщает одновременно «ветка №3» и «смерджено».
 */
@Immutable
enum class GraphEdgeRole {

  /** Магистраль: сплошная 2 dp, нейтральная — у корневой ветки идентичности нет. */
  Baseline,

  /** Линия ветки по её дорожке: 1.5 dp цветом идентичности. */
  Branch,

  /** Уход с магистрали на дорожку ветки: вертикаль, угол, горизонталь до первого узла (§6.4). */
  Fork,

  /** Возврат с дорожки в магистраль: горизонталь, угол, вертикаль до точки слияния (§6.6). */
  Merge,

  /**
   * Хвост незакрытой темы: линия, уходящая вправо и растворяющаяся (§6.8).
   *
   * Отдельной сущности у хвоста нет, хотя проект её предполагал. Причина отпала вместе с
   * привязкой к вьюпорту: пока конец хвоста зависел от камеры, его нельзя было посчитать в
   * раскладке вовсе, — а конец у правого края содержимого раскладке известен, и хвост стал
   * обычным ребром с собственной ролью.
   */
  Tail
}
