package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import java.time.LocalDateTime

/**
 * Узел до того, как стала известна его пауза.
 *
 * Существует потому, что [GraphNode.gap] — величина **соседская**: она считается от предыдущего узла
 * по времени, а кто предыдущий, выясняется только после того, как узлы всех веток сведены в один
 * список и отсортированы. Собирать узел сразу пришлось бы с заглушкой вместо паузы, а заглушка,
 * которую забыли заменить, — это ровно тот дефект, который на экране выглядит просто чуть другим
 * зазором.
 *
 * Здесь же лежит и содержимое узла: узел и то, что внутри него нарисовано, приходят из одного
 * кластера сообщений, и разложить их по двум спискам значило бы завести две вещи, которые обязаны
 * идти в одном порядке.
 *
 * @param id идентификатор узла: у эпизода — идентификатор его первого сообщения
 * @param branchId ветка, которой принадлежит узел; у точек на магистрали — корневая
 * @param role чем узел является для раскладки
 * @param at момент времени, по которому узел встаёт в общий порядок
 * @param episode содержимое плашки; `null` у точек на линии
 * @param preview содержимое превью-карточки; `null` у точек на линии
 */
@Immutable
internal data class GraphNodeDraft(
  val id: GraphNode.Id,
  val branchId: GraphBranch.Id,
  val role: GraphNodeRole,
  val at: LocalDateTime,
  val episode: GraphEpisode? = null,
  val preview: GraphNodePreview? = null
)
