package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import ru.sla.atlas.entity.Branch
import java.time.LocalDateTime

/**
 * Узел до того, как стала известна его пауза.
 *
 * Существует потому, что [Node.gap] — величина **соседская**: она считается от предыдущего узла по
 * времени, а кто предыдущий, выясняется только после того, как узлы всех веток сведены в один
 * список и отсортированы.
 *
 * Пауза внутри [node] поэтому не значит ничего, и заглушка здесь безопасна ровно по одной причине:
 * проставляет паузу единственный проход, и проставляет он её **каждому** узлу без разбора. Уцелеть
 * заглушке негде — не потому, что о ней помнят, а потому, что мимо этого прохода узел в граф не
 * попадает.
 *
 * Рядом лежат две величины, которых у самого узла нет: момент, по которому он встаёт в общий
 * порядок, и ветка, которой он принадлежит, — состав ветки собирается из этого поля, а узел своей
 * ветки не знает.
 *
 * @param node узел, каким он попадёт в граф: всё, кроме паузы
 * @param branchId ветка, которой принадлежит узел; у точек на магистрали — корневая
 * @param at момент времени, по которому узел встаёт в общий порядок
 * @param preview содержимое превью-карточки; `null` у точек на линии
 */
@Immutable
internal data class GraphNodeDraft(
  val node: Node,
  val branchId: Branch.Id,
  val at: LocalDateTime,
  val preview: GraphNodePreview? = null
)
