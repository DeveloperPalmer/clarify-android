package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Что нарисовано внутри превью-карточки узла (§11.2 брифа).
 *
 * Интерфейс, а не класс: экрану нужен только этот набор величин, а откуда он взялся — из
 * временного набора или из собранного графа — его не касается. Конкретный мок иначе протёк бы в
 * публичное состояние экрана и не смог бы остаться internal.
 *
 * Всё уже приведено к тому виду, в котором рисуется: время — строкой. Форматировать по дороге к
 * карточке нечего.
 *
 * Карточка эпизода разворачивает его **последнее** сообщение: текст плашки — это оно и есть, а §11.2
 * писался тогда, когда базовым узлом было сообщение, а не кластер.
 */
@Immutable
interface NodePreview {

  /** Имя автора сообщения. */
  val authorName: String

  /** Фото автора или `null`: тогда аватар рисует инициалы. */
  val authorPhotoUrl: String?

  /** Полный текст сообщения, без эллипсиса. */
  val text: String

  /** Время сообщения, готовое к показу. */
  val time: String
}
