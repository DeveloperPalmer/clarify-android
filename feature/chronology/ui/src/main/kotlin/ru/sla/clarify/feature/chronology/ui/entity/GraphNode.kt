package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Узел графа с точки зрения раскладки: где он стоит, но не что в нём нарисовано.
 *
 * Содержимое узла даёт вызывающий по [id] — полотну оно безразлично. Здесь только то, из чего
 * считается положение, чтобы раскладку можно было проверить юнит-тестом без Compose.
 *
 * **Дорожки у узла нет, и это решение с причиной.** Дорожка — результат раскладки, а не свойство
 * узла: она выводится из того, какие ветки живут одновременно, и переиспользуется после слияния
 * (§4.2 брифа). Пока номер дорожки лежал в узле, он был второй истиной — модель говорила одно,
 * раскладка считала другое, и разойтись они могли молча.
 *
 * @param id идентификатор узла, он же ключ композиции
 * @param branchId ветка, которой принадлежит узел; у магистрали она своя, как и у любой другой
 * @param role чем узел является для раскладки: плашкой или точкой на линии
 * @param gap пауза перед этим узлом относительно предыдущего узла списка
 */
@Immutable
data class GraphNode(
  val id: Id,
  val branchId: GraphBranch.Id,
  val role: GraphNodeRole,
  val gap: TimeGap
) {

  /** Идентификатор узла графа: ключ композиции и будущая цель перехода в чат. */
  @JvmInline
  value class Id(val value: String)
}
