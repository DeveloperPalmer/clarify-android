package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import ru.sla.atlas.entity.Node
import ru.sla.atlas.entity.TimeGap

/**
 * Узел графа беседы: и то, из чего считается его положение, и то, что внутри него нарисовано.
 *
 * Раскладочную половину узел берёт у [Node] — идентификатор и паузу, единственное, что о нём
 * знает граф. Всё остальное живёт здесь и различается по роду узла, потому что рода различаются не
 * оттенком, а составом: у эпизода есть время, счётчик и сниппет, у точки на линии нет ничего.
 */
@Immutable
sealed interface GraphNode : Node {

  /**
   * Место, которому есть что показать: кластер подряд идущих сообщений.
   *
   * **Карточка лежит внутри узла, а не отдельной картой рядом с графом.** Адресуется она
   * идентификатором узла, и карта, разъехавшаяся с графом хотя бы на кадр, развернула бы плашку в
   * чужой текст — **молча**. Полем эпизода карточка есть у каждого эпизода и только у него, а
   * стережёт это компилятор, а не аккуратность собирающего.
   *
   * @param id идентификатор первого сообщения кластера
   * @param gap пауза перед этим узлом относительно предыдущего узла графа
   * @param time время начала эпизода — время его первого сообщения
   * @param count число сообщений в кластере
   * @param text текст последнего сообщения эпизода; плашка обрезает его эллипсисом по своей ширине
   * @param myShare доля своих реплик, от нуля до единицы
   * @param unreadCount сколько сообщений эпизода осталось непрочитанными; ноль — читать нечего
   * @param dim эпизод внутри слитой ветки: рисуется приглушённым
   * @param preview содержимое превью-карточки. Величины у неё свои: время здесь — момент последнего
   *   сообщения, а не начала эпизода, и совпадение этих двух было бы случайным
   */
  @Immutable
  data class Episode(
    override val id: Node.Id,
    override val gap: TimeGap,
    val time: String,
    val count: Int,
    val text: String,
    val myShare: Float,
    val unreadCount: Long,
    val dim: Boolean,
    val preview: NodePreview
  ) : GraphNode {

    /** Состояние сообщения: определяет иконку справа от текста и прозрачность плашки. */
    enum class Status {
      Normal,
      Edited,
      Quoted,
      Sending
    }
  }

  /**
   * Место, откуда уходит ветка.
   *
   * @param id идентификатор узла
   * @param gap пауза перед этим узлом относительно предыдущего узла графа
   */
  @Immutable
  data class Fork(
    override val id: Node.Id,
    override val gap: TimeGap
  ) : GraphNode

  /**
   * Место на магистрали, где ветка вернулась в родителя.
   *
   * @param id идентификатор узла
   * @param gap пауза перед этим узлом относительно предыдущего узла графа
   */
  @Immutable
  data class Merge(
    override val id: Node.Id,
    override val gap: TimeGap
  ) : GraphNode {

    /**
     * Дошло ли слияние до конца.
     *
     * Два состояния, а не три: пока merge request открыт, места на магистрали нет вовсе — точка
     * появляется только с финализацией, и «запрошено» описывает не её, а ветку, см.
     * [ru.sla.atlas.entity.Branch.Status].
     */
    enum class Status {

      /**
       * Место на магистрали готово, слияние ещё не показано состоявшимся.
       *
       * Вне церемонии слияния это состояние живёт ровно столько, сколько играет её кадр «удар».
       */
      Pending,

      /** Слияние состоялось. */
      Done
    }
  }

  /**
   * Последний узел магистрали — «сейчас».
   *
   * @param id идентификатор узла
   * @param gap пауза перед этим узлом относительно предыдущего узла графа
   */
  @Immutable
  data class Front(
    override val id: Node.Id,
    override val gap: TimeGap
  ) : GraphNode
}
