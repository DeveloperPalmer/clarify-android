package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Оттенок идентичности ветки: какая это ветка, а не что с ней происходит (§7 брифа).
 *
 * **Перечисление, а не номер.** Оттенков ровно столько, сколько ролей объявила тема, и число это
 * жило в двух местах сразу: размером палитры у того, кто оттенок считает, и хвостом `else` у того,
 * кто превращает его в цвет. Разъехаться они могли только молча — седьмая роль от дизайнера
 * осталась бы недостижимой, а не сломала бы сборку. Теперь оба места считают по [entries], и
 * значение, забытое при раскрытии в цвет, не компилируется.
 *
 * Отсюда же и потолок: ветка берёт оттенок из этого набора и никакой другой. Повтор через каждые
 * шесть ветвлений неизбежен — счёт идёт за всю жизнь беседы, а оттенков конечное число, — и
 * допустим: цвет говорит «какая это ветка» соседям по экрану, а не всей истории.
 *
 * Значения названы номерами, а не дорожками и не цветами: дорожка переиспользуется после слияния и
 * ветке не принадлежит, а «синий» и «зелёный» — выбор темы, который она вправе поменять, не
 * спрашивая хронологию.
 */
@Immutable
enum class BranchColor {
  First,
  Second,
  Third,
  Fourth,
  Fifth,
  Sixth;

  companion object {

    /**
     * Оттенок ветки по её порядковому номеру.
     *
     * Номер — порядок ветвления по времени, а не номер дорожки: дорожка освобождается после слияния
     * и достаётся следующей ветке, и цвет, взятый из неё, означал бы «номер ряда», а не «какая это
     * тема».
     *
     * @param order порядковый номер ветки по времени ветвления, начиная с единицы
     * @return оттенок; после последнего набор идёт по кругу
     */
    fun ofOrder(order: Int): BranchColor {
      return entries[(order - 1).mod(entries.size)]
    }
  }
}
