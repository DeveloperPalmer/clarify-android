package ru.sla.clarify.feature.chronology.ui.components.canvas

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.unit.IntSize
import ru.sla.atlas.entity.Placement
import ru.sla.clarify.feature.chronology.ui.entity.GraphCameraRange
import ru.sla.clarify.feature.chronology.ui.entity.GraphPanStep

/*
 * Камера полотна: где ей разрешено быть, где она стоит в покое, как на неё ложится дельта и когда
 * инерцию пора обрывать.
 *
 * Отделено от раскладки намеренно. Раскладка отвечает, где стоят плашки, и о камере не знает
 * вовсе — а здесь ни одна функция не знает, как получились координаты плашек. Пока обе темы
 * лежали в одном файле, правка любой из них заставляла читать чужую.
 */

/**
 * Допустимый сдвиг содержимого, при котором любой центр плашки достижим центром экрана.
 *
 * По оси времени это и есть главная политика: в покое в центре экрана стоит самый левый узел, а
 * докрутив вправо до упора — самый правый. Кламп по одним лишь краям содержимого давал бы обратное:
 * начало истории у левой кромки, конец у правой.
 *
 * По вертикали та же политика нужна не ради покоя, а ради пинча: пока камере разрешалось лишь
 * держать содержимое прижатым к краям, зум над нижними плашками уводил их из-под пальцев — удержать
 * точку значило оторвать содержимое от кромки, чего кламп не позволял.
 *
 * @param centreSpan отрезок центров плашек по этой оси, в координатах полотна
 * @param viewport размер видимой области по той же оси
 * @return диапазон сдвига, вырожденный в точку при единственном узле
 */
internal fun centrePanRangeOf(
  centreSpan: ClosedFloatingPointRange<Float>,
  viewport: Float
): ClosedFloatingPointRange<Float> {
  val centre = viewport / 2f
  return (centre - centreSpan.endInclusive)..(centre - centreSpan.start)
}

/**
 * Допустимый сдвиг содержимого по одной оси.
 *
 * Камера — это сдвиг содержимого: `экран = полотно + камера`. Чтобы начало содержимого встало у
 * начала экрана, нужен сдвиг `-min`; чтобы конец встал у конца экрана — `viewport - max`.
 *
 * Когда содержимое короче экрана, границы меняются местами: содержимому разрешено гулять внутри
 * экрана, но не выходить за него. Схлопывать диапазон в одно центрирующее значение нельзя, хотя
 * такая запись и выглядит аккуратнее: защёлкнутая камера не может держать точку под пальцами, и
 * пинч над содержимым, которое помещается целиком, уводит плашку из-под разведённых пальцев тем
 * сильнее, чем дальше она от центра. На демо-наборе это начиналось ниже 0.572× — там, где граф
 * впервые влезал в экран по высоте.
 *
 * Центрирование от этого не пропадает: куда камера смотрит, пока её не двигали, отвечает
 * [cameraRestOf], и делает это наведением, а не запретом двигаться.
 *
 * Когда содержимого нет вовсе, двигать нечего и сдвиг остаётся нулевым — иначе пустое полотно
 * уезжало бы на пол-экрана.
 *
 * @param min начало содержимого в координатах полотна
 * @param max конец содержимого в координатах полотна
 * @param viewport размер видимой области по той же оси
 * @return диапазон сдвига; при помещающемся содержимом — от «начало у начала экрана» до «конец у
 *   конца экрана»
 */
internal fun panRangeOf(min: Float, max: Float, viewport: Float): ClosedFloatingPointRange<Float> {
  if (max <= min) {
    return 0f..0f
  }
  val lower = viewport - max
  // Именно `0f - min`, а не `-min`: у нуля унарный минус даёт отрицательный нуль, и граница
  // печаталась как «-0.0».
  val upper = 0f - min
  return if (lower <= upper) lower..upper else upper..lower
}

/**
 * Где камере разрешено быть при этой раскладке, этом вьюпорте и этом масштабе.
 *
 * Собирает обе оси в одну величину, чтобы «где камере можно быть» имело единственное определение:
 * то же самое значение читается при показе, проверяется при записи и пере-накладывается после
 * раскладки. Пока определение жило выражением внутри чтения, запись о нём не знала.
 *
 * Раскладка отдаёт координаты полотна, а камера живёт в пикселях экрана: слой ставит масштаб от
 * начала координат, то есть `экран = полотно · scale + камера`. Отсюда единственное место, где
 * масштаб вообще входит в арифметику камеры, — умножение границ содержимого здесь. Всё остальное —
 * шаг, покой, признак упора — считает в экранных пикселях и о масштабе не знает.
 *
 * Поля полотна масштабируются вместе с содержимым, потому что входят в [Placement.bounds].
 * Цена: системные врезки, лежащие в тех же полях, тоже сжимаются, и на самом мелком масштабе поле
 * снизу становится меньше кнопочной навигационной полосы — 64 dp поля плюс 48 dp полосы дают при
 * 0.4× сорок пять пикселей вместо сорока восьми. Обратный ход, если это увидят глазом: вынести
 * врезки из полей раскладки и раздувать ими диапазон уже здесь, в экранных пикселях.
 *
 * @param placement последняя раскладка графа
 * @param viewport размер видимой области
 * @param scale масштаб содержимого
 * @return диапазоны по обеим осям; вырожденные — норма, а не краевой случай
 */
internal fun cameraRangeOf(
  placement: Placement,
  viewport: IntSize,
  scale: Float
): GraphCameraRange {
  if (placement.isEmpty) {
    return GraphCameraRange.Empty
  }
  // На обеих осях разрешено то, что разрешает **любая** из двух политик: навести центр крайней
  // плашки в центр экрана — или прижать край содержимого к краю экрана. Пересечения здесь быть не
  // может: каждая описывает, что камере можно, и запрет одной не отменяет разрешение другой.
  //
  // Одной политики не хватает ни там, ни там, и обе нехватки вскрылись пинчем. По времени: граница
  // «первая плашка не правее центра экрана» уезжает вместе с масштабом, поле полотна перед плашкой
  // растёт, а показать его нельзя — точка уходила из-под пальцев на 399 px к 2.5×. По вертикали:
  // прижатое к кромкам содержимое не давало приподнять себя, и нижние плашки уползали вниз тем
  // сильнее, чем мельче масштаб.
  return GraphCameraRange(
    x = widestOf(
      centrePanRangeOf(
        centreSpan = placement.centreSpanX.scaledBy(scale),
        viewport = viewport.width.toFloat()
      ),
      panRangeOf(
        min = placement.bounds.left * scale,
        max = placement.bounds.right * scale,
        viewport = viewport.width.toFloat()
      )
    ),
    y = widestOf(
      centrePanRangeOf(
        centreSpan = placement.centreSpanY.scaledBy(scale),
        viewport = viewport.height.toFloat()
      ),
      panRangeOf(
        min = placement.bounds.top * scale,
        max = placement.bounds.bottom * scale,
        viewport = viewport.height.toFloat()
      )
    )
  )
}

/**
 * Отрезок координат полотна в пикселях экрана.
 *
 * @param scale масштаб содержимого
 * @return тот же отрезок, умноженный на масштаб
 */
private fun ClosedFloatingPointRange<Float>.scaledBy(scale: Float): ClosedFloatingPointRange<Float> {
  return (start * scale)..(endInclusive * scale)
}

/**
 * Объединение двух допустимых диапазонов по одной оси.
 *
 * Именно объединение, а не пересечение: каждая политика описывает, что камере **разрешено**, и
 * запретом одной не может быть разрешение другой. Пересечение обнулило бы диапазон там, где одна из
 * политик вырождена в точку, — а вырожденная ось на этом экране норма.
 *
 * @param first первый диапазон
 * @param second второй диапазон
 * @return диапазон, содержащий оба
 */
private fun widestOf(
  first: ClosedFloatingPointRange<Float>,
  second: ClosedFloatingPointRange<Float>
): ClosedFloatingPointRange<Float> {
  return minOf(first.start, second.start)..maxOf(first.endInclusive, second.endInclusive)
}

/**
 * Где камера стоит, пока её не двигали.
 *
 * Наводится на **первую** плашку, а не прижимается к краю содержимого: экран открывают, чтобы
 * увидеть начало истории, и оно должно оказаться под глазами, а не в углу. Наведение зажимается
 * диапазоном — у короткой истории центр экрана недостижим, и тогда камера встаёт настолько близко
 * к нему, насколько содержимое позволяет.
 *
 * Который из центров первый, решается здесь, а не в раскладке: раскладка отвечает, где стоят
 * плашки, и знать о том, что одна из них — начало истории, ей незачем.
 *
 * @param placement последняя раскладка графа
 * @param viewport размер видимой области
 * @param range где камере разрешено быть
 * @param scale масштаб содержимого
 * @return положение камеры в покое
 */
internal fun cameraRestOf(
  placement: Placement,
  viewport: IntSize,
  range: GraphCameraRange,
  scale: Float
): Offset {
  if (placement.isEmpty) {
    return Offset.Zero
  }
  return cameraAimedAt(
    point = placement.centres.first(),
    viewport = viewport,
    range = range,
    scale = scale
  )
}

/**
 * Камера, при которой [point] полотна оказывается в центре экрана.
 *
 * Одно определение наведения на всех: по нему стоит камера в покое, к нему же приводит перелёт по
 * кнопке. Второе определение того же движения разъехалось бы с первым при первой правке клампа —
 * и разъехалось бы молча, потому что оба выглядят как «поставить точку в середину».
 *
 * Наведение зажимается диапазоном: у короткой истории центр экрана недостижим, и камера встаёт
 * настолько близко к нему, насколько содержимое позволяет.
 *
 * @param point точка полотна в его собственных координатах
 * @param viewport размер видимой области
 * @param range где камере разрешено быть
 * @param scale масштаб содержимого
 * @return положение камеры, зажатое диапазоном
 */
internal fun cameraAimedAt(
  point: Offset,
  viewport: IntSize,
  range: GraphCameraRange,
  scale: Float
): Offset {
  return cameraPuttingPointAt(
    point = point,
    screen = Offset(x = viewport.width / 2f, y = viewport.height / 2f),
    range = range,
    scale = scale
  )
}

/**
 * Камера, при которой [point] полотна оказывается в точке [screen] экрана.
 *
 * Общая форма наведения: [cameraAimedAt] — её частный случай, где экранная точка это середина. Второй
 * записи того же правила в коде нет и быть не должно — обе выглядели бы как «поставить точку куда
 * надо», а разъехались бы на первой правке клампа.
 *
 * Общей форме нашлось дело у смены уровня детализации: якорь перехода стоит под пальцами, а не под
 * центром экрана, и середина там — чужое место.
 *
 * @param point точка полотна в его собственных координатах
 * @param screen точка экрана, под которой она обязана оказаться
 * @param range где камере разрешено быть
 * @param scale масштаб содержимого
 * @return положение камеры, зажатое диапазоном
 */
internal fun cameraPuttingPointAt(
  point: Offset,
  screen: Offset,
  range: GraphCameraRange,
  scale: Float
): Offset {
  return range.clamp(screen - point * scale)
}

/**
 * Двигает камеру на [delta], не выпуская её за [range].
 *
 * Кламп стоит на записи, а не на чтении, и это не перестановка мест. Накапливая незажатый сдвиг,
 * состояние банкует перерегулирование: упор в стенку на три тысячи пикселей превращается в мёртвую
 * зону такой же величины, которая сама не рассасывается — жест обратно сначала выбирает её и только
 * потом двигает картинку. Вылезает это не залипанием, а телепортом: следующая раскладка расширяет
 * диапазон, и камера за кадр уезжает на величину банка.
 *
 * @param camera текущий сдвиг содержимого
 * @param delta запрошенное приращение
 * @param range где камере разрешено быть
 * @return новый сдвиг и та часть [delta], которая в него уместилась
 */
internal fun panStepOf(camera: Offset, delta: Offset, range: GraphCameraRange): GraphPanStep {
  val moved = Offset(
    x = (camera.x + delta.x).coerceIn(range.x),
    y = (camera.y + delta.y).coerceIn(range.y)
  )
  return GraphPanStep(
    requested = delta,
    camera = moved,
    consumed = moved - camera
  )
}

/**
 * Масштаб, к которому приводит перелёт по кнопке камеры.
 *
 * Возвращает к покою только **сверху вниз**. Приблизившийся видел кусок истории вблизи, и перелёт
 * через весь граф на таком масштабе высаживает его в такой же кусок, только другой, — сбрасывать
 * зум тут и значит «показать, куда прилетели». Отдалившийся, наоборот, смотрит обзорно намеренно, и
 * приближать его насильно нельзя: он не просил менять масштаб, он просил сменить место.
 *
 * **Покой приходит числом, а не выводится здесь.** Он у каждого уровня детализации свой: где-то
 * единица означает «узел нарисован в свою величину», а где-то не означает ничего — там покой это
 * «видно всё», то есть нижний край полосы. Пока функция знала одну единицу на всех, перелёт с
 * обзора сажал камеру в масштаб, которого никто не просил, и делал это молча; а перечисляя уровни,
 * камера знала бы то, чего ей знать незачем.
 *
 * @param scale масштаб на момент нажатия
 * @param restScale покой, к которому уровень возвращается
 * @return покой, если было приближено; тот же масштаб в остальных случаях
 */
internal fun flightScaleOf(scale: Float, restScale: Float): Float {
  return if (scale > restScale) restScale else scale
}

/**
 * Масштаб после шага пинча, не выпущенный за [range].
 *
 * Масштаб зажимается **до** того, как под него пересчитают камеру, и порядок здесь существеннее, чем
 * кажется: посчитав камеру под запрошенный масштаб, а показав зажатый, полотно поехало бы под
 * пальцами каждый раз, когда зум упирается в границу.
 *
 * Не-конечный множитель отбрасывается целиком. Он приходит не из UX, а из арифметики жеста:
 * [androidx.compose.foundation.gestures.calculateZoom] делит размеры центроида, и на вырожденном
 * событии частное обращается в `NaN`, который `coerceIn` пропускает наружу молча.
 *
 * @param scale текущий масштаб
 * @param change множитель, пришедший от жеста
 * @param range разрешённые пределы масштаба
 * @return новый масштаб внутри пределов
 */
internal fun scaleStepOf(
  scale: Float,
  change: Float,
  range: ClosedFloatingPointRange<Float>
): Float {
  val requested = scale * change
  if (!requested.isFinite()) {
    return scale
  }
  return requested.coerceIn(range)
}

/**
 * Камера, при которой точка под фокусом остаётся под фокусом после смены масштаба.
 *
 * Прямое следствие того, как слой складывает масштаб со сдвигом: `экран = полотно · scale + камера`.
 * Точка полотна под фокусом равна `(focus − камера) / from`, и требование «остаться на месте» после
 * перехода к `to` даёт `focus − (focus − камера) · to / from`.
 *
 * @param camera текущий сдвиг содержимого
 * @param focus точка экрана, которую жест держит на месте
 * @param from масштаб до шага
 * @param to масштаб после шага
 * @return сдвиг, сохраняющий точку под фокусом
 */
internal fun zoomedCameraOf(camera: Offset, focus: Offset, from: Float, to: Float): Offset {
  if (from <= 0f) {
    return camera
  }
  return focus - (focus - camera) * (to / from)
}

/**
 * Масштаб фона при данном масштабе графа.
 *
 * Фон отстаёт от графа и по сдвигу, и по масштабу — с одним и тем же [BACKDROP_PARALLAX]. Два разных
 * правила для одной глубины разъехались бы при первой правке любого из них.
 *
 * @param scale масштаб содержимого
 * @return масштаб узора: 0.82 при 0.4× графа, 1.45 при 2.5×
 */
internal fun backdropScaleOf(scale: Float): Float {
  return 1f + (scale - 1f) * BACKDROP_PARALLAX
}

/**
 * Упёрлась ли камера по всем осям, которые несут бросок.
 *
 * Признак смотрит на диапазон и на направление, а не на то, сколько взяла последняя дельта, и это
 * важнее, чем кажется. Первый кадр затухания приходит с нулевым приращением, и правило вида
 * «потребили меньше запрошенного» остановило бы бросок, не начав его. Оно же не умеет отличить
 * упор от оси, которая в броске просто не участвует.
 *
 * Условие `&&` — осознанный отход от платформы. Платформа гасит диагональ целиком, стоит упереться
 * одной оси; здесь вертикальный ход бывает в разы короче горизонтального — при одной дорожке это
 * пустота внутри экрана, — поэтому любой слегка наклонный бросок умирал бы почти сразу, и «fling на
 * 360» работал бы ровно для одного угла. Пока бросок несёт хоть одна ось, инерция живёт и едет вдоль
 * стенки — как список, а не как стена.
 *
 * Цена решения: на вырожденной оси бросок проезжает только свою проекцию, но тратит на неё полную
 * длительность. Для пологих бросков это незаметно, для крутых — 80° дают 112 dp за те же 924 мс.
 * Если на устройстве это прочтётся как заедание, обратный ход — заменить `&&` на `||`.
 *
 * @param camera текущий сдвиг содержимого
 * @param direction единичный вектор броска, см. [FlingDirection]
 * @param range где камере разрешено быть
 * @return `true`, когда двигаться некуда и затухание пора обрывать
 */
internal fun isCameraStuck(camera: Offset, direction: Offset, range: GraphCameraRange): Boolean {
  return isAxisStuck(
    camera = camera.x,
    direction = direction.x,
    range = range.x
  ) && isAxisStuck(
    camera = camera.y,
    direction = direction.y,
    range = range.y
  )
}

/**
 * Упёрлась ли одна ось.
 *
 * Нулевая компонента направления и вырожденный диапазон — одно и то же: нести бросок этой оси нечем.
 *
 * @param camera сдвиг по этой оси
 * @param direction компонента направления броска
 * @param range допустимый сдвиг по этой оси
 * @return `true`, когда по этой оси ехать некуда
 */
private fun isAxisStuck(
  camera: Float,
  direction: Float,
  range: ClosedFloatingPointRange<Float>
): Boolean {
  if (direction == 0f || range.start >= range.endInclusive) {
    return true
  }
  return if (direction > 0f) {
    camera >= range.endInclusive
  } else {
    camera <= range.start
  }
}

