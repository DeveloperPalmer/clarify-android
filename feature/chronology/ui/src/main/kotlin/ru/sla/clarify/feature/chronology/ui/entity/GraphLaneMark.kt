package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Засечка ветки на мини-карте: где по времени начинается дорожка.
 *
 * Статус ветки здесь не хранится, и это решение, а не упущение. §7 брифа разводит две оси
 * кодирования: цвет — идентичность ветки, паттерн штриха и терминатор — её статус. На засечке
 * размером 2 × 12 dp паттерна нет, значит нет и статуса; смешать их в одном цвете означало бы, что
 * зелёная засечка сообщает одновременно «ветка №3» и «смерджено».
 *
 * @param position начало дорожки, долей содержимого от нуля до единицы
 * @param lane номер дорожки: цвет идентичности выводится из него, см. `Int.toLaneColor`
 */
@Immutable
data class GraphLaneMark(
  val position: Float,
  val lane: Int
)
