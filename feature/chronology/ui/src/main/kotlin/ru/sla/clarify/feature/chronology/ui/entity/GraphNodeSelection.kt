package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.geometry.Rect
import androidx.compose.ui.unit.Dp
import ru.sla.atlas.entity.BasicNode

/**
 * Выбранный узел: что показать в карточке и откуда она вырастает.
 *
 * Один объект, а не три поля состояния, потому что это один факт: карточка открыта **на этом узле**.
 * Порознь они разъехались бы — и разъехались бы молча, потому что каждое по отдельности выглядит
 * осмысленным.
 *
 * **Геометрия здесь заморожена намеренно.** Прямоугольник снимается у полотна в момент тапа и больше
 * не пересчитывается: живое значение пришлось бы читать при измерении якоря, то есть подписать
 * измерение на масштаб камеры — ровно то, чего полотно избегает у себя. Заморозка законна, пока
 * камера под открытой карточкой стоит; стоит она потому, что полотно на это время жестов не берёт.
 *
 * @param id узел, на котором открыта карточка: полотно по нему же и прячет плашку, чтобы поверхность
 *   уехала в карточку, а не размножилась
 * @param preview содержимое карточки
 * @param bounds где плашка нарисована на экране — в координатах полотна, уже с учётом масштаба
 * @param corner скругление плашки на экране: у него тот же масштаб, что у [bounds], иначе морф на
 *   2.5× стартовал бы с углами вчетверо острее нарисованных
 */
@Immutable
data class GraphNodeSelection(
  val id: BasicNode.Id,
  val preview: NodePreview,
  val bounds: Rect,
  val corner: Dp
)
