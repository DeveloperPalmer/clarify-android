package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Что происходит с веткой — с точки зрения того, как рисуется её линия (§7 брифа).
 *
 * Второй статус рядом с [BranchNodeStatus] заведён намеренно, и причина не в педантизме. Тот
 * описывает **строку на плашке** и несёт вместе с состоянием число дней молчания — величину,
 * которая меняется по календарю и к геометрии отношения не имеет. Линии же нужно ровно два
 * признака: сплошная она или пунктирная и с какой прозрачностью.
 *
 * Разделять пришлось ещё и потому, что занятость дорожки читает отсюда [Abandoned]: брошенная тема
 * дорожку отдаёт, а замороженная открытым merge request — держит.
 */
@Immutable
enum class GraphBranchStatus {

  /** Тема живёт: merge request не открыт. Линия сплошная. */
  Alive,

  /** Merge request открыт и ждёт одобрений. Линия пунктирная, ветка заморожена, но жива. */
  Waiting,

  /** Одобрен обоими — осталось завершить слияние. Узор пунктира тот же, но бежит вдоль линии. */
  Ready,

  /** Тема закрыта. Линия сплошная, приглушённая. */
  Merged,

  /** Тему бросили: сообщений нет дольше тридцати дней. Линия гаснет сильнее прочих. */
  Abandoned
}
