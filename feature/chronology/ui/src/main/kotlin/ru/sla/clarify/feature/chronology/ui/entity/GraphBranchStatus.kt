package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable

/**
 * Что происходит с веткой: и то, как рисуется её линия (§7 брифа), и то, что написано в строке
 * статуса на её узле (§6.5).
 *
 * **Тип один, и раньше их было два.** `BranchNodeStatus` держался на состоянии «заброшена»: он
 * носил внутри дни молчания — величину, которая меняется по календарю и к геометрии линии отношения
 * не имеет. Владелец состояние отменил (журнал, итерация 39), и от второго типа осталось то же
 * множество под другими именами. Два имени одного множества — вторая истина, которая расходится
 * молча: правило про линию правят в одном, правило про строку остаётся в другом.
 *
 * Разводить снова стоит тогда, и только тогда, когда появится состояние, касающееся **лишь одной**
 * из двух сторон, — например кадр церемонии слияния, у которого есть вид, но нет строки.
 *
 * Четыре состояния собираются из трёх доменных: `MergeRequest` у ветки может не быть вовсе
 * ([Alive]), может быть открыт ([Waiting]), готов ([Ready]) или завершён ([Merged]). Поэтому статус
 * и есть сущность экрана, а не доменный `enum`, вынесенный в `ui`: «Обсуждается» — это отсутствие
 * merge request, а не одно из его состояний.
 */
@Immutable
enum class GraphBranchStatus {

  /** Тема живёт: merge request не открыт. Линия сплошная. */
  Alive,

  /** Merge request открыт и ждёт одобрений. Линия пунктирная, ветка заморожена, но жива. */
  Waiting,

  /** Одобрен обоими — осталось завершить слияние. Узор пунктира тот же, но бежит вдоль линии. */
  Ready,

  /** Тема закрыта, ветка стала read-only. Линия сплошная, приглушённая; непрочитанное остаётся. */
  Merged
}
