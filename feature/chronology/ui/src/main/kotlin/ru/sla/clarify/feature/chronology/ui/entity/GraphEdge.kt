package ru.sla.clarify.feature.chronology.ui.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.geometry.Offset

/**
 * Ребро графа: ортогональная ломаная в координатах полотна.
 *
 * **Числа, а не `Path`.** Готовый `Path` был бы удобнее рисованию, но `androidx.compose.ui.graphics.Path`
 * на Android — обёртка над `android.graphics.Path`, чьи методы в `android.jar` являются стабами:
 * Robolectric в проекте нет, и функция, отдающая `Path`, юнит-тестом не покрывается вовсе. Вся
 * арифметика этой фичи, оставшаяся без теста, рано или поздно ломалась, поэтому маршрут считается
 * числами, а `Path` собирается уже в фазе рисования.
 *
 * Соседние точки [points] всегда отличаются ровно одной координатой: маршрут ортогонален по
 * построению, а не по договорённости (§7 брифа). Двух точек хватает отрезку, трёх — Г-образному
 * уходу или возврату.
 *
 * Ребро живёт строго в зазоре между плашками: узел бывает полупрозрачным, и линия под ним
 * просвечивала бы. Исключение — точки на магистрали: они залиты непрозрачно именно затем, чтобы
 * прорезать линию, и маршрут ветки начинается от их центра.
 *
 * @param points точки излома в порядке следования линии
 * @param hops координаты X чужих вертикалей, над которыми этот маршрут ставит мостики (§18.1)
 * @param colorIndex цвет идентичности ветки, см. `Int.toBranchColor`
 * @param role чем ребро является: от этого зависит только толщина
 * @param status что с веткой происходит: от этого зависит только штрих и прозрачность
 */
@Immutable
data class GraphEdge(
  val points: List<Offset>,
  val hops: List<Float>,
  val colorIndex: Int,
  val role: GraphEdgeRole,
  val status: GraphBranchStatus
)
