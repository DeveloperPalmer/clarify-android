/**
 * Куда уходит ветка от точки ветвления (§6.4 брифа).
 *
 * Дорожки занимаются по очереди вверх и вниз от магистрали, поэтому направление у точки ветвления
 * ровно два. Шеврон-указатель над узлом повёрнут соответственно — он и есть то, что сообщает
 * направление до того, как читатель проследит линию.
 */
enum class ForkDirection {
  Up,
  Down
}
