package ru.sla.clarify.entity.chat

/**
 * Элемент живого потока: что произошло с элементом и его данные. Только для стримов —
 * у разового чтения понятия «тип изменения» нет, оно отдаёт данные напрямую.
 *
 * [isPending] — данные ещё не подтверждены сервером: локальная оптимистичная запись,
 * которую поток отдал раньше ответа.
 *
 * Тип назван в доменных терминах намеренно: пока изменение зовётся по поставщику,
 * второго поставщика в репозиторий не подставить — имя типа в сигнатуре называет
 * источник данных, и точки подмены не существует.
 */
data class ChatChange<T>(
  val changeType: Type,
  val data: T,
  val isPending: Boolean = false
) {

  enum class Type {
    Added,
    Modified,
    Removed
  }
}
