package ru.sla.atlas.layout

import androidx.compose.runtime.Immutable

/**
 * Вертикальный отрезок ребра: то, над чем горизонтали ставят мостики.
 *
 * Заведён затем, чтобы поиск пересечений был чистой арифметикой, а не обходом готовых маршрутов:
 * вертикали собираются один раз при построении ветвлений и возвратов, а потом проверяются против
 * каждой горизонтали.
 *
 * @param x координата вертикали в координатах полотна
 * @param fromY начало отрезка по вертикали
 * @param toY конец отрезка по вертикали
 */
@Immutable
data class Vertical(
  val x: Float,
  val fromY: Float,
  val toY: Float
)
