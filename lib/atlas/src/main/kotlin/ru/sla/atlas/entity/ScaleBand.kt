package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable

/**
 * Полоса масштаба уровня: где уровень живёт и за какими краями сменяется соседним.
 *
 * Полоса принадлежит уровню, а не полотну, и это главное её свойство. Сырой масштаб между уровнями
 * несравним — на сжатой раскладке 2.3× показывает столько же истории, сколько 0.4× на подробной,
 * — поэтому «пределы зума» перестают быть одним числом на полотно и становятся свойством уровня.
 *
 * @param min нижний край: ниже него полотно уходит на соседний уровень
 * @param max верхний край: выше него — тоже
 */
@Immutable
data class ScaleBand(
  val min: Float,
  val max: Float
)
