package ru.sla.atlas.lod

import androidx.compose.ui.unit.Dp
import ru.sla.atlas.entity.ScaleBand
import ru.sla.atlas.entity.TimeGap

/**
 * Что полотну нужно знать об уровнях детализации вызывающего.
 *
 * **Тип уровня задаёт вызывающий** — тот же приём, что и с узлом: движок объявляет минимум, который
 * ему нужен, а какие уровни бывают и как они называются, знает та сторона, которая их показывает.
 * Пока уровень был перечислением фичи, шесть файлов движка знали, что уровня ровно два.
 *
 * **Шесть ответов держатся в одном месте, и это главное свойство схемы.** Порядок уровней и их
 * метрики — одно знание, разложенное надвое: список, упорядоченный «от грубого к детальному», не
 * проверяется ни компилятором, ни тестом, а перепутанный порядок уводит щипок в ту же сторону, в
 * которую он и вёл. Здесь же новый уровень не компилируется сразу везде, где о нём надо было
 * рассказать.
 *
 * Полотно без уровней детализации — не ветка в движке, а схема из одного уровня: оба соседа у него
 * `null`, полоса одна, и переходить некуда.
 *
 * @param L уровень детализации вызывающего
 */
interface LevelScheme<L> {

  /**
   * Расстояние между соседними дорожками на этом уровне.
   *
   * @param level уровень детализации
   * @return шаг дорожки
   */
  fun laneStepOf(level: L): Dp

  /**
   * Зазор, которым пауза отделяет узел от предыдущего.
   *
   * Отдельно от шага дорожки, потому что спрашивают их в разных местах измерения: шаг — один раз на
   * раскладку, зазор — на каждый узел.
   *
   * @param level уровень детализации
   * @param gap пауза перед узлом
   * @return расстояние от предыдущего узла
   */
  fun stepWidthOf(level: L, gap: TimeGap): Dp

  /**
   * Полоса масштаба уровня: где он живёт и за какими краями сменяется соседним.
   *
   * Зависит от вписывания, а не только от уровня: у обзорного уровня нижний край и есть «видно
   * всё», а насколько это мелко, решает длина истории. Поэтому полоса считается по месту, а не
   * хранится: содержимое меняется, и хранимая полоса разошлась бы с ним молча.
   *
   * @param level уровень детализации
   * @param fitScale масштаб, при котором содержимое видно целиком, см. [fitScaleOf]
   * @return пределы, за которыми уровень сменяется соседним
   */
  fun bandOf(level: L, fitScale: Float): ScaleBand

  /**
   * Масштаб покоя уровня: тот, к которому возвращает перелёт камеры.
   *
   * Единицы на всех не бывает: где-то она означает «узел нарисован в свою величину», а где-то не
   * означает ничего — там покой это нижний край полосы.
   *
   * @param level уровень детализации
   * @param band полоса этого уровня, см. [bandOf]
   * @return масштаб, ниже которого перелёт не опускает
   */
  fun restScaleOf(level: L, band: ScaleBand): Float

  /**
   * Соседний уровень крупнее охватом: туда уводит щипок ниже полосы.
   *
   * **Лестница конечна:** идя по соседям в одну сторону, рано или поздно приходишь к `null`. На
   * этом стоит поиск самого обзорного уровня — то, во что упирается «вписать всё», — и замкнутая в
   * кольцо схема этот поиск подвесит.
   *
   * @param level уровень детализации
   * @return соседний уровень или `null`, если этот — самый обзорный
   */
  fun coarserThan(level: L): L?

  /**
   * Соседний уровень мельче охватом: туда уводит щипок выше полосы.
   *
   * @param level уровень детализации
   * @return соседний уровень или `null`, если этот — самый подробный
   */
  fun finerThan(level: L): L?
}
