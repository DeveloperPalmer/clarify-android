package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable

/**
 * Ветка графа с точки зрения раскладки: где она крепится к магистрали и как долго держит дорожку.
 *
 * **Идентичность ветки живёт здесь, а не в номере дорожки.** Дорожка освобождается после слияния и
 * достаётся следующей ветке — только поэтому граф не разрастается вниз бесконечно, — а значит номер
 * дорожки принадлежит не ветке, а отрезку времени. Пока ветку опознавали по дорожке, две
 * несвязанные темы, вставшие на один ряд по очереди, оказывались для графа одной и той же веткой —
 * и разъезжалось от этого молча всё, что ветку ищет.
 *
 * Цвет берётся из [colorIndex], а не из дорожки. Ноль зарезервирован за магистралью, поэтому
 * вызывающий обязан считать индекс со сдвигом: наивный остаток от деления рано или поздно выдаёт
 * ветке цвет магистрали.
 *
 * @param id идентификатор ветки
 * @param nodeIds узлы ветки в том же порядке, в каком они лежат в [Graph.nodes]; состав ветки —
 *   её собственное знание, и других мест, где он записан, нет
 * @param forkedFrom узел магистрали, от которого ветка ушла; `null`, когда узла ветвления нет —
 *   он удалён или ещё не догружен
 * @param mergedAt узел магистрали, в котором ветка слилась; `null` у всех несмерженных
 * @param status что с веткой происходит; [Status.Merged] — единственное состояние, отдающее дорожку
 * @param colorIndex цвет идентичности: `0` у магистрали, дальше — по числу оттенков палитры
 */
@Immutable
data class Branch(
  val id: Id,
  val nodeIds: List<BasicNode.Id>,
  val forkedFrom: BasicNode.Id?,
  val mergedAt: BasicNode.Id?,
  val status: Status,
  val colorIndex: Int
) {

  /** Идентификатор ветки: ключ группировки узлов и адрес самой ветки для вызывающего. */
  @JvmInline
  value class Id(val value: String)

  /**
   * Где ветка находится на пути к слиянию.
   *
   * **Тип один, и разводить его на два не нужно.** Наборов было два — свой у того, кто ветку
   * показывает, и свой у того, кто её называет словами, — и оба перечисляли одно и то же множество
   * разными именами. Вторая истина расходится молча: состояние, заведённое в одном наборе, во
   * втором просто не появляется, и ветка молча получает вид соседнего состояния.
   *
   * Разводить стоит тогда, и только тогда, когда появится состояние, существующее лишь для одной
   * из сторон.
   *
   * Состояния говорят, **что** с веткой стало, а не чем это вызвано: граф знает «живёт», «ждёт»,
   * «готова», «слита», а откуда вызывающий это взял — merge request, решение участника или что-то
   * ещё — его дело и его слой.
   */
  @Immutable
  enum class Status {

    /** Ветка растёт: слияние не запрошено. */
    Alive,

    /** Слияние запрошено, решение не принято: ветка заморожена, но жива. */
    Waiting,

    /** Решение принято, слияние не завершено. */
    Ready,

    /** Ветка слита и дальше не растёт: только это освобождает её дорожку. */
    Merged
  }
}
