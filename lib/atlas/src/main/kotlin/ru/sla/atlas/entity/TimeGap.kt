package ru.sla.atlas.entity

/**
 * Квантованная пауза между соседями.
 *
 * Ось X полотна — порядковое время, а не абсолютное: реальная длительность паузы растянула бы ночь
 * на километры пустоты. Точная длительность выводится подписью, расстояние даёт только порядок
 * величины.
 */
enum class TimeGap {
  Minutes,
  Hour,
  Hours,
  Day,
  Long
}
