package ru.sla.atlas.layout

import androidx.compose.runtime.Immutable

/**
 * Всё, что выводится из порядка узлов и списка веток: на какой дорожке стоит узел и чем он окрашен.
 *
 * Две величины лежат вместе, потому что считаются **одним** назначением дорожек веткам. Порознь их
 * считали два вызова, и каждый строил заново индекс узлов, отрезки занятости и жадную раскраску, —
 * то есть измерение платило за одну и ту же работу дважды за кадр.
 *
 * Дорожка узла и дорожка его акцента — разные числа, и потому обе здесь и лежат: точка ветвления
 * стоит на магистрали, её собственная дорожка нулевая, а акцент показывает дорожку уходящей ветки.
 * Вывести одно из другого нельзя ни в одну сторону.
 *
 * @param lanes номер дорожки каждого узла, в порядке узлов
 * @param accents цвет и направление каждого узла, в том же порядке
 */
@Immutable
data class Lanes(
  val lanes: List<Int>,
  val accents: List<NodeAccent>
)
