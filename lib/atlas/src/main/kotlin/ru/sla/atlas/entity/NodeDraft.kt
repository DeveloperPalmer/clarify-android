package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable
import java.time.LocalDateTime

/**
 * Узел до того, как стала известна его пауза.
 *
 * Существует потому, что [Node.gap] — величина **соседская**: она считается от предыдущего узла
 * по времени, а кто предыдущий, выясняется только после того, как узлы всех веток сведены в один
 * список и отсортированы. Пауза внутри [node] поэтому не значит ничего: её проставит сборка, и
 * проставит **каждому** узлу без разбора.
 *
 * Рядом лежат две величины, которых у самого узла нет: момент, по которому он встаёт в общий
 * порядок, и ветка, которой он принадлежит, — состав ветки собирается из этого поля, а узел своей
 * ветки не знает.
 *
 * @param N узел вызывающего
 * @param node узел, каким он попадёт в граф: всё, кроме паузы
 * @param branchId ветка, которой принадлежит узел
 * @param at момент времени, по которому узел встаёт в общий порядок
 * @param order разрешение спора внутри одного момента: меньший идёт раньше. Совпадение моментов —
 *   не экзотика, а обычное дело, и чем оно разрешается, знает только вызывающий
 */
@Immutable
data class NodeDraft<out N : Node>(
  val node: N,
  val branchId: Branch.Id,
  val at: LocalDateTime,
  val order: Int = 0
)
