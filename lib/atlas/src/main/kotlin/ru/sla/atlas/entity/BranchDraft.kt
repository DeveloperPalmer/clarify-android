package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable

/**
 * Ветка до того, как стал известен её состав.
 *
 * Существует по той же причине, что и [NodeDraft]: состав — величина **сводная**. Он складывается
 * из того, какой ветке принадлежит каждый узел, и до сортировки узлов его нет ни у кого, включая
 * саму ветку. Вызывающему поэтому нечего в него положить, и он клал туда пустоту — [Branch] с
 * пустым составом означает «ветка без узлов», а не «состав ещё не посчитан», и эти две разные вещи
 * выглядели одинаково в каждом вызове сборки.
 *
 * Разница с [Branch] ровно в одном поле, и второй тип заведён ради него: ветку с выдуманным
 * составом теперь не построить — [Graph] ловил такую в конструкторе, но уже как ошибку данных, а
 * здесь её нечем выразить.
 *
 * @param id идентификатор ветки
 * @param forkedFrom узел магистрали, от которого ветка ушла; `null`, когда узла ветвления нет —
 *   он удалён или ещё не догружен
 * @param mergedAt узел магистрали, в котором ветка слилась; `null` у всех несмерженных
 * @param status что с веткой происходит
 */
@Immutable
data class BranchDraft(
  val id: Branch.Id,
  val forkedFrom: Node.Id?,
  val mergedAt: Node.Id?,
  val status: Branch.Status
)
