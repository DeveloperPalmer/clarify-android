package ru.sla.atlas.layout

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Чем узел окрашен и куда смотрит: то, что нужно нарисовать узел, но не нужно, чтобы его разложить.
 *
 * Заведено потому, что акцент узла не выводится из его собственной дорожки. Узел, на котором ветка
 * ушла с магистрали или вернулась в неё, стоит **на магистрали**, а показывать обязан ту ветку,
 * о которой говорит: иначе он был бы нейтральным, а всё, что висит рядом с ним, не знало бы, с
 * какой стороны магистрали ему быть.
 *
 * Считается вместе с дорожками и по тем же данным, а не выводится узлом на месте: знать, какая
 * ветка от него ушла, узлу неоткуда, и цвет он получает готовым.
 *
 * @param lane дорожка, на которую смотрит узел: у плашки своя, у точки — дорожка её ветки. Знак
 *   говорит, с какой стороны магистрали живёт ветка
 * @param color цвет идентичности ветки, за которую узел говорит
 */
@Immutable
data class NodeAccent(
  val lane: Int,
  val color: Color
)
