package ru.sla.atlas.layout

import androidx.compose.runtime.Immutable
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.graphics.Color
import ru.sla.atlas.entity.Branch

/**
 * Ребро графа: ортогональная ломаная в координатах полотна.
 *
 * **Числа, а не `Path`.** Готовый `Path` был бы удобнее рисованию, но
 * `androidx.compose.ui.graphics.Path` на Android — обёртка над `android.graphics.Path`, чьи методы в
 * `android.jar` являются стабами: без Robolectric функция, отдающая `Path`, юнит-тестом не
 * покрывается вовсе. Арифметика раскладки, оставшаяся без теста, рано или поздно ломается, поэтому
 * маршрут считается числами, а `Path` собирается уже в фазе рисования.
 *
 * Соседние точки [points] всегда отличаются ровно одной координатой: маршрут ортогонален по
 * построению, а не по договорённости. Двух точек хватает отрезку, трёх — Г-образному уходу или
 * возврату.
 *
 * Ребро живёт строго в зазоре между узлами: узел бывает полупрозрачным, и линия под ним
 * просвечивала бы. Исключение — узлы, на которых ветка уходит с магистрали и возвращается в неё:
 * маршрут ветки начинается от их центра, потому что залиты они непрозрачно и линию прорезают собой.
 *
 * **Ветку опознаёт [branchId], а не [color].** Оттенков у вызывающего конечное число, а счёт веток
 * идёт за всю жизнь графа, поэтому цвет неизбежно повторяется: две ветки одного оттенка живут
 * одновременно, на разных дорожках и в разных концах истории. Всё, что ищет рёбра одной ветки,
 * обязано спрашивать идентификатор; поиск по цвету нашёл бы вдобавок чужую линию и не упал бы при
 * этом ни разу.
 *
 * @param points точки излома в порядке следования линии
 * @param hops координаты X чужих вертикалей, которые этот маршрут пересекает: рисующий обходит их
 *   мостиком, а раскладка отвечает только на то, где они встретились
 * @param branchId чья это линия; у магистрали — идентификатор корневой ветки, а не `null`
 * @param color цвет идентичности ветки
 * @param role чем ребро является для читающего граф
 * @param status что происходит с веткой, которой ребро принадлежит
 */
@Immutable
data class Edge(
  val points: List<Offset>,
  val hops: List<Float>,
  val branchId: Branch.Id,
  val color: Color,
  val role: EdgeRole,
  val status: Branch.Status
)
