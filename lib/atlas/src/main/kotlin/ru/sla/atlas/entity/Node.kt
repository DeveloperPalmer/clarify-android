package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable

/**
 * Точка на полотне: то, из чего считается её положение.
 *
 * Узел — единица раскладки, и раскладке от него нужны ровно две вещи: чем отличить его от соседа и
 * насколько от соседа отодвинуть. Чем узел является для читателя и что внутри него нарисовано,
 * знает вызывающий: свой тип узла он подставляет в [Graph] сам.
 */
@Immutable
interface Node {

  /** Идентификатор узла. */
  val id: Id

  /** Пауза перед этим узлом относительно предыдущего узла списка. */
  val gap: TimeGap

  /**
   * Идентификатор узла.
   *
   * Объявлен здесь, а не у наследника: ссылаются по нему [Branch] и [Graph] — та половина
   * графа, которая о наследнике ничего не знает.
   */
  @JvmInline
  value class Id(val value: String)
}
