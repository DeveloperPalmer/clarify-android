package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable

/**
 * Поля полотна вокруг содержимого, в пикселях.
 *
 * По сторонам они разные, и это не украшение. Полотно, занимающее весь экран, живёт и под тем, что
 * система рисует поверх него сверху и снизу, — и увести оттуда крайние узлы должны поля, а не
 * размер полотна. У боковых краёв такого соседа нет, поэтому одинаковое поле со всех сторон
 * означало бы либо узел под чужим элементом, либо лишнюю пустоту слева и справа.
 *
 * Чем именно занята верхняя и нижняя полосы, поля не знают: они принимают уже посчитанные числа.
 *
 * @param left поле слева
 * @param top поле сверху
 * @param right поле справа
 * @param bottom поле снизу
 */
@Immutable
data class CanvasMargins(
  val left: Float,
  val top: Float,
  val right: Float,
  val bottom: Float
) {

  companion object {

    /** Полотно без полей: содержимое доходит до самой кромки. */
    val Zero = CanvasMargins(left = 0f, top = 0f, right = 0f, bottom = 0f)
  }
}
