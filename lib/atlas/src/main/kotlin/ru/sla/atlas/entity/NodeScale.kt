package ru.sla.atlas.entity

import java.time.Duration

/**
 * Чем меряется пауза между узлами и как она попадает в узел.
 *
 * **Шкала — свойство вызывающего, а не одной сборки.** Ступени зазора у разных полотен разные: где-то
 * час — это ещё «та же беседа», где-то уже следующая ступень. Библиотека их не выбирает и не хранит,
 * она только спрашивает — как и об уровнях детализации, см. [ru.sla.atlas.lod.LevelScheme].
 *
 * Обе половины лежат в одном типе, потому что порознь ни одна ничего не решает: [gapOf] считает
 * ступень, [withGap] её проставляет, и сборка вызывает их подряд на каждый узел. Пока они были двумя
 * лямбдами в списке параметров, каждый вызов сборки писал их заново — а меняться от вызова к вызову
 * им не с чего.
 *
 * @param N узел вызывающего
 */
interface NodeScale<N : Node> {

  /**
   * Ступень зазора, которой пауза отделит узел от предыдущего.
   *
   * @param duration пауза перед узлом относительно соседа по времени
   * @return ступень зазора
   */
  fun gapOf(duration: Duration): TimeGap

  /**
   * Тот же узел с проставленной паузой.
   *
   * @param node узел, каким его подал вызывающий
   * @param gap пауза, посчитанная по соседу слева
   * @return узел, готовый попасть в граф; идентификатор обязан сохраниться — по нему ветки и
   *   находят свои узлы
   */
  fun withGap(node: N, gap: TimeGap): N
}
