package ru.sla.atlas.entity

/**
 * Куда камера умеет перелетать одним движением.
 *
 * Перечисление, а не пара методов у держателя: мест, к которым осмысленно возвращаться, будет
 * больше — «вы здесь», линия непрочитанного, открытый merge request, — и каждое такое место должно
 * добавляться одной строкой здесь, а не новым методом с собственной копией перелёта.
 */
enum class Anchor {

  /** Исток — самое начало истории. */
  Start,

  /** Фронт — последнее по времени, что в графе есть. */
  Front
}
