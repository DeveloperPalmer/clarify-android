package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.geometry.Offset

/**
 * Заявка на посадку после смены уровня: что запомнить в жесте, чтобы разобрать в измерении.
 *
 * Существует потому, что охват нового уровня выводится из его раскладки, а её в момент жеста ещё
 * нет: зазоры считает измерение, и `centreSpanX` появляется только там. Записать масштаб посадки
 * сразу нельзя, а ждать кадр — значит показать сжатую раскладку в старом масштабе, то есть тот самый
 * телепорт, ради которого всё это и делается.
 *
 * Уровень в заявке не хранится: он уже записан в состояние, и второе его место разошлось бы с первым.
 *
 * @param anchorIndex узел, ближайший к точке под пальцами; индекс валиден на обоих уровнях, потому
 *   что список узлов уровень не меняет
 * @param anchorScreen место экрана, под которым этот узел обязан остаться
 * @param spanBefore охват уходящего уровня — отрезок центров плашек в его координатах
 * @param scaleBefore масштаб, на котором полотно ушло с прошлого уровня
 */
@Immutable
data class LevelSwitch(
  val anchorIndex: Int,
  val anchorScreen: Offset,
  val spanBefore: Float,
  val scaleBefore: Float
)
