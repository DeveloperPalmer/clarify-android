package ru.sla.atlas.layout

import androidx.compose.runtime.Immutable

/**
 * Чем ребро является для читающего граф.
 *
 * Роль отвечает за то, что линия означает, и только за это. Цвет берётся из идентичности ветки,
 * штрих — из её статуса: три независимые оси, и смешать их значило бы, что одна линия сообщает
 * сразу «чья она», «что с ней» и «что она соединяет» одним и тем же признаком.
 *
 * Чем каждая роль нарисована, решает рисующий: здесь описано, что она значит.
 */
@Immutable
enum class EdgeRole {

  /** Магистраль: ветка, от которой уходят остальные. */
  Baseline,

  /** Линия ветки по её собственной дорожке. */
  Branch,

  /** Уход с магистрали на дорожку ветки: вертикаль, угол, горизонталь до первого узла ветки. */
  Fork,

  /** Возврат с дорожки в магистраль: горизонталь, угол, вертикаль до узла слияния. */
  Merge,

  /**
   * Хвост несмерженной ветки: линия от её последнего узла до правого края содержимого.
   *
   * Отдельной сущности у хвоста нет, хотя она напрашивается. Причина отпала вместе с привязкой к
   * вьюпорту: пока конец хвоста зависел от камеры, посчитать его в раскладке было нельзя вовсе, —
   * а конец у правого края содержимого раскладке известен, и хвост стал обычным ребром с
   * собственной ролью.
   */
  Tail
}
