package ru.sla.atlas.entity

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

/**
 * Засечка ветки на мини-карте: где по времени начинается дорожка.
 *
 * Статус ветки здесь не хранится, и это решение, а не упущение. Цвет кодирует идентичность ветки, а
 * что с ней происходит, показывает штрих её линии; на засечке в пару пикселей штриха нет, значит
 * нет и статуса. Смешать их в одном цвете означало бы, что зелёная засечка сообщает одновременно
 * «ветка такая-то» и «слита».
 *
 * **Направление и цвет — два разных числа, и свести их в одно нельзя.** Дорожка говорит, куда
 * рисовать засечку — вверх или вниз, — а цвет принадлежит ветке: дорожка переиспользуется после
 * слияния, и две разные ветки, вставшие на неё по очереди, обязаны отличаться. Пока цвет
 * выводился из номера дорожки, они получали один оттенок, и **компилятор об этом молчал** — обе
 * величины были `Int`. Теперь не молчит: цвет типизирован цветом.
 *
 * @param position начало дорожки, долей содержимого от нуля до единицы
 * @param lane номер дорожки: задаёт только направление засечки от полосы
 * @param color цвет идентичности ветки
 */
@Immutable
data class LaneMark(
  val position: Float,
  val lane: Int,
  val color: Color
)
